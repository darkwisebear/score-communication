//! Publisher GAT workaround (Plan B, Problem 1).
//!
//! mockall 0.14 cannot `#[automock]` a trait with a generic associated type.
//! Scriptable decisions live on the lifetime-free [`PublisherPolicy`]; this
//! module's hand-written types are the only place that names
//! `SampleMaybeUninit<'a>`. Copy this split for `Subscription`.
//!
//! Construction:
//! - Tests of the wrapper itself: [`MockPublisherImpl::from_policy`].
//! - Code generated by `interface!`: [`Publisher::new`] pops a policy from
//!   [`crate::MockRegistry`].

use crate::provider_info::ProviderInfoHandle;
use crate::registry::lookup;
use crate::runtime::MockRuntimeImpl;
use core::fmt::{self, Debug};
use core::mem::MaybeUninit;
use core::ops::{Deref, DerefMut};
use mockall::automock;
use score_com_concept::{CommData, Publisher, Result, SampleMaybeUninit, SampleMut};
use std::sync::{Arc, Mutex};

/// Lifetime-free, automockable policy for [`MockPublisherImpl`].
///
/// `allocate` is the scriptable decision behind [`Publisher::allocate`].
/// `send` is called from [`SampleMut::send`] with the fully written value.
#[automock]
pub trait PublisherPolicy<T: CommData + Debug + 'static>: Send + 'static {
    fn allocate(&self) -> Result<()>;
    fn send(&self, value: T) -> Result<()>;
}

/// Uninitialized sample buffer. No scriptable behavior of its own.
pub struct MockSampleMaybeUninit<'a, T: CommData + Debug> {
    data: MaybeUninit<T>,
    policy: Arc<Mutex<MockPublisherPolicy<T>>>,
    _lifetime: core::marker::PhantomData<&'a ()>,
}

impl<'a, T: CommData + Debug> AsMut<MaybeUninit<T>> for MockSampleMaybeUninit<'a, T> {
    fn as_mut(&mut self) -> &mut MaybeUninit<T> {
        &mut self.data
    }
}

impl<'a, T: CommData + Debug> Debug for MockSampleMaybeUninit<'a, T> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("MockSampleMaybeUninit").finish_non_exhaustive()
    }
}

impl<'a, T: CommData + Debug> SampleMaybeUninit<T> for MockSampleMaybeUninit<'a, T> {
    type SampleMut = MockSampleMut<'a, T>;

    fn write(self, value: T) -> Self::SampleMut {
        MockSampleMut {
            data: value,
            policy: self.policy,
            _lifetime: core::marker::PhantomData,
        }
    }

    unsafe fn assume_init(self) -> Self::SampleMut {
        MockSampleMut {
            data: unsafe { self.data.assume_init() },
            policy: self.policy,
            _lifetime: core::marker::PhantomData,
        }
    }
}

/// Initialized sample buffer. `send` forwards to [`PublisherPolicy::send`].
pub struct MockSampleMut<'a, T: CommData + Debug> {
    data: T,
    policy: Arc<Mutex<MockPublisherPolicy<T>>>,
    _lifetime: core::marker::PhantomData<&'a ()>,
}

impl<'a, T: CommData + Debug> Deref for MockSampleMut<'a, T> {
    type Target = T;

    fn deref(&self) -> &Self::Target {
        &self.data
    }
}

impl<'a, T: CommData + Debug> DerefMut for MockSampleMut<'a, T> {
    fn deref_mut(&mut self) -> &mut Self::Target {
        &mut self.data
    }
}

impl<'a, T: CommData + Debug> Debug for MockSampleMut<'a, T> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("MockSampleMut").field("data", &self.data).finish()
    }
}

impl<'a, T: CommData + Debug> SampleMut<T> for MockSampleMut<'a, T> {
    fn send(self) -> Result<()> {
        self.policy.lock().expect("poisoned").send(self.data)
    }
}

/// Hand-written `Publisher` wrapper. The GAT lives only here.
pub struct MockPublisherImpl<T: CommData + Debug> {
    policy: Arc<Mutex<MockPublisherPolicy<T>>>,
}

impl<T: CommData + Debug> MockPublisherImpl<T> {
    /// Test-only constructor: skip the registry and wrap an already-scripted
    /// policy.
    pub fn from_policy(policy: MockPublisherPolicy<T>) -> Self {
        Self {
            policy: Arc::new(Mutex::new(policy)),
        }
    }
}

impl<T: CommData + Debug> Publisher<T, MockRuntimeImpl> for MockPublisherImpl<T> {
    type SampleMaybeUninit<'a>
        = MockSampleMaybeUninit<'a, T>
    where
        Self: 'a;

    fn allocate(&self) -> Result<Self::SampleMaybeUninit<'_>> {
        self.policy.lock().expect("poisoned").allocate()?;
        Ok(MockSampleMaybeUninit {
            data: MaybeUninit::uninit(),
            policy: Arc::clone(&self.policy),
            _lifetime: core::marker::PhantomData,
        })
    }

    fn new(identifier: &str, instance_info: ProviderInfoHandle) -> Result<Self> {
        let policy =
            lookup::publisher::<T>(&instance_info.registry, &instance_info.instance, identifier)
                .unwrap_or_else(|| {
                    panic!(
                        "no MockPublisherPolicy registered for instance '{}' event '{}'",
                        instance_info.instance.as_ref(),
                        identifier
                    )
                });
        Ok(Self { policy })
    }
}

#[cfg(test)]
mod test {
    use super::*;
    use crate::registry::MockRegistry;
    use mockall::predicate::eq;
    use score_com_concept::{
        AllocationFailureReason, Error, InstanceSpecifier, Publisher,
    };

    #[derive(Debug, Clone, PartialEq)]
    #[repr(C)]
    struct TestData {
        value: i32,
    }

    unsafe impl score_com_concept::Reloc for TestData {}

    impl score_com_concept::CommData for TestData {
        const ID: &'static str = "TestData";
    }

    fn test_spec() -> InstanceSpecifier {
        InstanceSpecifier::new("/Test/Service1/Instance").expect("valid instance specifier")
    }

    #[test]
    fn publisher_allocate_error_is_injected() {
        let mut policy = MockPublisherPolicy::<TestData>::new();
        policy.expect_allocate().times(1).returning(|| {
            Err(Error::AllocateError(
                AllocationFailureReason::InvalidRequest,
            ))
        });

        let publisher = MockPublisherImpl::from_policy(policy);
        let err = publisher.allocate().unwrap_err();
        assert!(matches!(
            err,
            Error::AllocateError(AllocationFailureReason::InvalidRequest)
        ));
    }

    #[test]
    fn publisher_send_matches_argument_via_write() {
        let payload = TestData { value: 42 };
        let mut policy = MockPublisherPolicy::<TestData>::new();
        policy.expect_allocate().times(1).returning(|| Ok(()));
        policy
            .expect_send()
            .with(eq(payload.clone()))
            .times(1)
            .returning(|_| Ok(()));

        let publisher = MockPublisherImpl::from_policy(policy);
        let sample = publisher.allocate().expect("allocate");
        sample.write(payload).send().expect("send");
    }

    #[test]
    fn publisher_send_shortcut_scripts_allocate_and_send() {
        let payload = TestData { value: 7 };
        let mut policy = MockPublisherPolicy::<TestData>::new();
        policy.expect_allocate().times(1).returning(|| Ok(()));
        policy
            .expect_send()
            .with(eq(payload.clone()))
            .times(1)
            .returning(|_| Ok(()));

        let publisher = MockPublisherImpl::from_policy(policy);
        publisher.send(payload).expect("Publisher::send");
    }

    #[test]
    fn publisher_new_takes_policy_from_registry() {
        let spec = test_spec();
        let registry = MockRegistry::new();
        let mut policy = MockPublisherPolicy::<TestData>::new();
        policy.expect_allocate().times(1).returning(|| Ok(()));
        registry.expect_publisher(&spec, "left_tire", policy);

        let info = ProviderInfoHandle::from_policy(
            spec,
            registry,
            crate::provider_info::MockProviderInfoPolicy::new(),
        );
        let publisher = MockPublisherImpl::<TestData>::new("left_tire", info)
            .expect("Publisher::new should take the registered policy");
        publisher.allocate().expect("scripted allocate");
    }

    #[test]
    #[should_panic(
        expected = "no MockPublisherPolicy registered for instance '/Test/Service1/Instance' event 'left_tire'"
    )]
    fn registry_miss_panics_with_context() {
        let info = ProviderInfoHandle::from_policy(
            test_spec(),
            MockRegistry::new(),
            crate::provider_info::MockProviderInfoPolicy::new(),
        );
        let _ = MockPublisherImpl::<TestData>::new("left_tire", info);
    }
}
